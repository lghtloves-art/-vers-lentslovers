// Utilitaire pour déterminer le "poème du jour" de façon déterministe
export function getPoemOfTheDay(poems: Poem[]): Poem {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) /
      (1000 * 60 * 60 * 24),
  );
  const index = dayOfYear % poems.length;
  return poems[index];
}
